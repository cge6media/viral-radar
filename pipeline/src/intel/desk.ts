/**
 * Creator Action Desk (4.0) — "If I have 30 minutes to two hours today, which opportunity is worth pursuing?"
 *
 * Opportunities are clusters (microtrends / formats) that passed the evidence bar AND are a repeatable kind of
 * attention (format or meme; a calendar event only as "participate selectively"). Each one carries the real
 * supporting videos, the measured facts, a timing stage, a production feasibility judgement for a creator who
 * works with AI generation / animation / characters / editing / music in ≤ 2 hours, the plausible monetization
 * channels, and ONE recommended action. The ranking uses the owner's stated profile; general discovery is not
 * restricted by it (the full trend list stays available).
 *
 * Nothing here is generated by a language model at runtime: every sentence is assembled from measured facts.
 */
import type { DeskAction, DeskEvidence, DeskOpportunity, DeskReport, DeskTiming, Trend, TrendFeatures, VideoRecord } from '../types.js';
import { profileFor } from './taxonomy.js';
import { exampleKey } from './cluster.js';
import { titleMatchesFormat } from './formats.js';
import { clamp, hoursBetween, round } from '../lib/util.js';

export const CREATOR_PROFILE = {
  languages: ['en', 'es'],
  tools: ['ai-video', 'animation', 'characters', 'editing', 'music'],
  maxHours: 2,
  goal: 'direct revenue from views and streams; repeatable, original formats',
};

const fmt = (n: number) => (n >= 1e6 ? `${(n / 1e6).toFixed(1)}M` : n >= 1e3 ? `${(n / 1e3).toFixed(n >= 1e4 ? 0 : 1)}K` : `${Math.round(n)}`);
const LATIN = new Set(['en', 'es', 'pt', 'fr', 'de', 'it', 'latin', 'id', 'tl', 'vi', 'tr']);

/** categories by how well AI/animation/editing production fits them (0..1) */
const CATEGORY_FIT: Record<string, number> = {
  'Animation & Art': 1, 'Comedy': 0.9, 'Entertainment': 0.8, 'Music': 0.85, 'Animals & Pets': 0.7, 'Tech & AI': 0.75, 'Education': 0.6, 'Gaming': 0.55, 'Kids & Family': 0.75,
  'Film & TV': 0.5, 'Food & Cooking': 0.35, 'Lifestyle': 0.35, 'Beauty & Fashion': 0.25, 'Fitness & Health': 0.3, 'Sports': 0.2, 'News & Politics': 0.05, 'Business & Finance': 0.35, 'Travel': 0.2, 'Science': 0.55,
};

export function timingOf(t: Trend, now: string): { timing: DeskTiming; why: string; score: number } {
  const w = t.windows['7d'];
  const g = w.growth.basis === 'measured' ? w.growth.ratio : undefined;
  const ageDays = hoursBetween(t.firstDetected, now) / 24;
  const gTxt = g != null ? `measured ${g}× over ${w.growth.windowHours}h` : 'growth not yet measured';
  if (ageDays >= 7 && g != null && g >= 1.5) return { timing: 'resurfacing', why: `First seen ${Math.round(ageDays)} days ago and ${gTxt} — attention is coming back.`, score: 65 };
  switch (w.lifecycle) {
    case 'emerging': return { timing: 'emerging', why: `${w.newCreators} creators joined in the last 48h; ${gTxt}.`, score: g != null && g < 1 ? 45 : 80 };
    case 'accelerating': return { timing: 'accelerating', why: `${gTxt}; ${w.newCreators} new creators in 48h.`, score: 90 };
    case 'breaking_out': return { timing: 'accelerating', why: `Momentum on ${t.platforms.length} sources; ${gTxt}.`, score: 85 };
    case 'peaking': return g != null && g >= 1.15 ? { timing: 'established', why: `High, still-growing attention (${gTxt}).`, score: 60 } : { timing: 'peaking', why: `Attention is high but flat (${gTxt}).`, score: 40 };
    case 'cooling': return { timing: 'cooling', why: `Attention is falling (${gTxt}).`, score: 15 };
    default: return { timing: 'emerging', why: 'Evidence still forming.', score: 35 };
  }
}

export function fitScore(t: Trend, f: TrendFeatures): { fit: number; approach: string[]; feasible: boolean; why: string; effort: [number, number] } {
  const cat = CATEGORY_FIT[t.category] ?? 0.5;
  const h = f.hooks;
  const n = Math.max(1, f.videos);
  const share = (k: string) => (h[k] || 0) / n;
  const approach: string[] = [];
  let tool = 0;
  if (share('animated') >= 0.2 || t.category === 'Animation & Art') { tool += 0.5; approach.push('animated or AI-generated characters and scenes'); }
  if (share('ai') >= 0.15) { tool += 0.3; approach.push('AI-generated video (text-to-video / image-to-video) with original characters'); }
  if (share('character') >= 0.15) { tool += 0.3; approach.push('a recurring original character (consistent design, voice and catchphrase)'); }
  if (share('music') >= 0.2 || t.category === 'Music') { tool += 0.3; approach.push('original music or an original parody track (no copyrighted audio)'); }
  if (share('storytime') >= 0.2) { tool += 0.15; approach.push('a short scripted story with a voiceover'); }
  if (share('pov') >= 0.15 || share('when') >= 0.15) { tool += 0.15; approach.push('a relatable "POV / when…" setup acted by a character'); }
  if (share('versus') >= 0.15 || share('escalation') >= 0.15) { tool += 0.1; approach.push('an escalating comparison or a ladder of levels'); }
  if (share('transformation') >= 0.15) { tool += 0.1; approach.push('a before → after reveal with a satisfying payoff'); }
  if (share('reaction') >= 0.4) { tool -= 0.2; approach.push('(reaction-heavy: use an original character reacting, not a repost)'); }
  if (share('tutorial') >= 0.3) { tool += 0.05; approach.push('an explainer told by a character, in under 60 seconds'); }
  if (!approach.length) approach.push('an original short-form skit using AI characters and fast editing');
  const langs = f.languages;
  const totalLang = Object.values(langs).reduce((a, b) => a + b, 0) || 1;
  const enEs = ((langs.en || 0) + (langs.es || 0)) / totalLang;
  const latinShare = Object.entries(langs).filter(([k]) => LATIN.has(k)).reduce((a, [, v]) => a + v, 0) / totalLang;
  const langFit = enEs >= 0.5 ? 1 : latinShare >= 0.5 ? 0.7 : 0.35;
  const typeFit = t.opportunity?.type === 'format' ? 1 : t.opportunity?.type === 'meme' ? 0.8 : t.opportunity?.type === 'event' ? 0.3 : 0.4;
  const shortForm = f.shortsShare >= 0.5 || (f.medianDurationSec ?? 61) <= 60;
  const feasible = cat >= 0.35 && !['Sports', 'News & Politics', 'Travel'].includes(t.category) && (shortForm || cat >= 0.7);
  const effort: [number, number] = shortForm ? [0.5, 2] : [1.5, 4];
  const fit = round(100 * clamp(0.35 * cat + 0.25 * clamp(tool, 0, 1) + 0.2 * langFit + 0.2 * typeFit, 0, 1), 0);
  const why = feasible
    ? `${t.category} fits AI/animation production; ${shortForm ? 'short-form examples (median ' + (f.medianDurationSec ? Math.round(f.medianDurationSec) + 's' : 'under a minute') + ')' : 'longer examples'}; ${enEs >= 0.5 ? 'mostly English/Spanish' : latinShare >= 0.5 ? 'Latin-script languages (adapt the wording)' : 'mostly non-Latin-script content — adapt the concept, not the words'}.`
    : `${t.category} is hard to produce originally with AI/animation in two hours${shortForm ? '' : ' and the examples are long-form'}.`;
  return { fit, approach, feasible, why, effort };
}

export function monetizationFor(t: Trend, f: TrendFeatures): DeskOpportunity['monetization'] {
  const p = profileFor(t.category);
  const shortForm = f.shortsShare >= 0.5 || (f.medianDurationSec ?? 61) <= 60;
  const platforms = shortForm ? ['YouTube Shorts', 'TikTok', 'Instagram Reels'] : ['YouTube', 'Facebook'];
  const mechanisms = shortForm
    ? ['YouTube Shorts ad-revenue share (Partner Program)', 'TikTok Creator Rewards (videos ≥ 1 min)', 'Facebook/Instagram content monetization']
    : ['YouTube watch-page ads (Partner Program)', 'Facebook in-stream ads'];
  if (t.category === 'Music' || (f.hooks.music || 0) >= Math.max(2, f.videos * 0.3)) mechanisms.push('streams of the original track (distribution to Spotify/Apple), Content ID on re-uses');
  if (p.sponsorship >= 0.6) mechanisms.push('brand integrations once the format has an audience');
  if (p.affiliate >= 0.5) mechanisms.push('affiliate links in the description');
  const eligibility = [
    'YouTube Partner Program: 1,000 subscribers + 10M public Shorts views in 90 days (or 4,000 watch hours) — Shorts RPM is far below long-form',
    'TikTok Creator Rewards: 10,000 followers, 100,000 views in 30 days, original videos over one minute',
    'Reused or AI-mass-produced content can be ineligible under YouTube\'s "inauthentic content" policy — the execution must be original',
  ];
  return { platforms, mechanisms, eligibility, suitability: t.monetizationSuitability };
}

function evidenceFor(t: Trend, byObs: Map<string, VideoRecord>): DeskEvidence[] {
  const seen = new Set<string>();
  const out: DeskEvidence[] = [];
  const videos = t.evidence.filter((e) => e.kind === 'video');
  const nameToks = t.name.replace(/^#/, '').toLowerCase().split(/\s+/).filter((x) => x.length >= 3);
  const sig = new Set([...nameToks, ...(t.opportunity?.features.signature || [])]);
  const matches = (title: string) => { const l = title.toLowerCase(); return (t.kind === 'format' ? titleMatchesFormat(t, title) : Array.from(sig).some((x) => l.includes(x))) ? 1 : 0; };
  const scale = (r?: VideoRecord) => (r?.verified && ((r.metrics.views || 0) >= 10_000 || (r.metrics.likes || 0) >= 200) ? 1 : 0);
  const ranked = videos.map((e) => ({ e, r: byObs.get(e.id) })).sort((a, b) => scale(b.r) - scale(a.r) || matches(b.e.title) - matches(a.e.title) || ((b.r?.metrics.views ?? b.r?.metrics.likes ?? 0) - (a.r?.metrics.views ?? a.r?.metrics.likes ?? 0)));
  for (const { e, r } of ranked) {
    const k = exampleKey(e);
    if (seen.has(k)) continue;
    seen.add(k);
    const v = r?.velocity?.[0];
    out.push({ id: e.id, platform: r?.platform || (e.video?.platform as DeskEvidence['platform']) || 'other', url: r?.url || e.url, title: (r?.title || e.title).slice(0, 110), creator: r?.creator?.name || e.creator?.name, thumbnail: r?.thumbnail || e.thumbnail, publishedAt: r?.publishedAt || e.videoPublishedAt, ageHours: r?.ageHours, views: r?.metrics.views, likes: r?.metrics.likes, velocityPerHour: v?.perHour, velocityHours: v?.hours, state: r?.state || 'unverified_signal', kind: r?.kind, verified: !!r?.verified, durationSec: r?.durationSec, language: r?.language });
    if (out.length >= 6) break;
  }
  return out;
}

function decideAction(t: Trend, f: TrendFeatures, timing: DeskTiming, fit: ReturnType<typeof fitScore>, evidenceScore: number, scaleOk: boolean): { action: DeskAction; why: string } {
  const type = t.opportunity?.type;
  const grade = t.windows['7d'].grade;
  if (!scaleOk && type !== 'event') return { action: 'monitor', why: 'Real adoption but small numbers so far (no example above 100K views / 1K likes).' };
  if (timing === 'cooling') return { action: 'skip', why: 'Attention is falling; a new entry would arrive after the audience moved on.' };
  if (type === 'event' && f.nameShape === 'calendar') return fit.fit >= 50 ? { action: 'participate', why: 'A calendar moment: worth one original piece on the day, not a series.' } : { action: 'skip', why: 'A calendar moment outside what AI/animation production does well.' };
  if (type === 'event') return { action: fit.feasible ? 'monitor' : 'skip', why: 'One video carries the attention; watch whether other creators adopt it before building a format on it.' };
  if (!fit.feasible) return { action: 'research', why: `Strong evidence but ${fit.why}` };
  if (grade === 'early' || f.creators < 4) return { action: 'monitor', why: `Only ${f.creators} independent creators so far — promising, not yet proven.` };
  if (timing === 'peaking') return { action: 'participate', why: 'Crowded and flat: only with a sharp original angle.' };
  if (timing === 'established' && t.kind === 'format' && t.isGeneric) {
    if (fit.fit >= 65 && evidenceScore >= 55) return { action: 'create_today', why: `An evergreen format with ${f.creators} independent creators this week; it fits ${fit.effort[0]}–${fit.effort[1]}h of AI/animation production — the opportunity is the current signature and your execution.` };
    if (fit.fit >= 45) return { action: 'research', why: 'Evergreen and active, but only a moderate fit for AI/animation production — study the current signature before committing.' };
    return { action: 'monitor', why: 'Evergreen, but a weak fit for the creator profile.' };
  }
  if ((timing === 'emerging' || timing === 'accelerating' || timing === 'resurfacing' || timing === 'established') && evidenceScore >= 55 && fit.fit >= 55) {
    return { action: 'create_today', why: `${f.creators} independent creators, ${timing} attention, and a format that fits ${fit.effort[0]}–${fit.effort[1]}h of AI/animation production.` };
  }
  if (evidenceScore >= 55) return { action: 'research', why: 'The evidence is solid but the creator fit is moderate — study the examples before committing production time.' };
  return { action: 'monitor', why: 'Evidence still developing.' };
}

export function buildDesk(trends: Trend[], records: VideoRecord[], now: string): DeskReport {
  const byObs = new Map(records.map((r) => [r.id, r]));
  const excluded: Record<string, number> = {};
  const skip = (why: string) => { excluded[why] = (excluded[why] || 0) + 1; };
  const out: DeskOpportunity[] = [];
  let considered = 0;
  for (const t of trends) {
    if (t.kind === 'topic') continue;
    considered++;
    const op = t.opportunity;
    const w = t.windows['7d'];
    if (!op) { skip('not classified'); continue; }
    if (t.isNewsEvent) { skip('news / person event'); continue; }
    if (w.grade === 'insufficient') { skip('insufficient evidence'); continue; }
    if (op.features.nameShape === 'fragment') { skip('title fragment, not a format'); continue; }
    if (op.features.liveShare >= 0.3) { skip('live streams, not a video format'); continue; }
    if (op.type === 'uncertain') { skip(t.isGeneric || op.features.descriptor ? 'generic tag or category' : 'no recognisable structure yet'); continue; }
    // evergreen format pools are allowed without a measured shift when adoption is broad (repeatable by definition)
    const evergreen = t.kind === 'format' && t.isGeneric;
    if (!t.qualified && op.type !== 'event' && !(evergreen && w.creators >= 6 && w.grade !== 'early')) { skip('not qualified (generic without measured shift)'); continue; }
    if (evergreen && w.creators > 80) { skip('category-level activity (too broad to be one opportunity)'); continue; }
    const f = op.features;
    const timing = timingOf(t, now);
    if (evergreen && timing.timing === 'peaking') { timing.timing = 'established'; timing.why = `Evergreen format: ${w.creators} independent creators this week (${w.newCreators} new in 48h); ${timing.why.replace(/^Attention is high but flat/, 'attention is high and steady')}`; timing.score = 55; }
    const fit = fitScore(t, f);
    const evidenceScore = round(clamp(0.35 * w.confidence + 0.25 * Math.min(100, 12 * f.creators) + 0.2 * (w.directVideos ? 100 : 30) + 0.2 * op.confidence, 0, 100), 0);
    const evidence = evidenceFor(t, byObs);
    const top = evidence[0];
    const scaleOk = evidence.some((e) => (e.views || 0) >= 100_000 || (e.platform === 'bluesky' && (e.likes || 0) >= 1_000));
    const { action, why: actionWhy } = decideAction(t, f, timing.timing, fit, evidenceScore, scaleOk);
    if (action === 'skip') { skip(`skipped: ${timing.timing === 'cooling' ? 'cooling' : 'single event'}`); continue; }
    const why: string[] = [];
    why.push(`${f.creators} independent creators posted ${f.videos} videos in 7 days${f.newCreators48h ? ` — ${f.newCreators48h} of them joined in the last 48h` : ''}.`);
    if (top?.views) why.push(`Best example: ${fmt(top.views)} views ${top.ageHours != null ? `in ${top.ageHours < 48 ? Math.round(top.ageHours) + 'h' : Math.round(top.ageHours / 24) + ' days'}` : ''}${top.velocityPerHour ? `, gaining +${fmt(top.velocityPerHour)}/h measured` : ''}.`);
    if (w.growth.basis === 'measured') why.push(`Measured ${w.growth.metric}: ${w.growth.ratio}× over ${w.growth.windowHours}h.`);
    if (f.repeatCreators) why.push(`${f.repeatCreators} creator${f.repeatCreators === 1 ? '' : 's'} repeat the format — a sign it works more than once.`);
    if (f.signature.length) why.push(`Recognisable signature in titles: ${f.signature.slice(0, 4).join(', ')}.`);
    if (t.platforms.length > 1) why.push(`Seen on ${t.platforms.join(', ')}.`);
    const caution = f.dominance >= 0.5 && f.videos >= 3 ? `${Math.round(f.dominance * 100)}% of the attention is one video${top ? ` (“${top.title.slice(0, 50)}”)` : ''} — the format is less proven than the headline number.`
      : op.type === 'meme' ? 'Memes decay fast: the window is days, not weeks.'
        : evergreen && w.growth.basis === 'measured' && (w.growth.ratio ?? 1) < 1.5 ? 'An evergreen format: always active, so the opportunity is the current signature and your execution, not a new wave.' : undefined;
    const score = round(0.4 * evidenceScore + 0.3 * timing.score + 0.3 * fit.fit, 0);
    out.push({
      id: `desk:${t.id}`, trendId: t.id, name: t.name.replace(/^#/, ''), category: t.category, type: op.type, typeConfidence: op.confidence,
      timing: timing.timing, timingWhy: timing.why, evidence, why,
      facts: { creators: f.creators, newCreators48h: f.newCreators48h, videos: f.videos, directVideos: f.directVideos, growth: w.growth.basis === 'measured' ? w.growth.ratio : undefined, growthBasis: w.growth.basis, topViews: top?.views, topVelocity: top?.velocityPerHour, grade: w.grade },
      features: f,
      production: { feasibleIn2h: fit.feasible && fit.effort[1] <= 2, approach: fit.approach, why: fit.why, effortHours: fit.effort },
      monetization: monetizationFor(t, f),
      action, actionWhy, fit: fit.fit, evidenceScore, timingScore: timing.score, score, caution,
    });
  }
  const order: Record<DeskAction, number> = { create_today: 0, participate: 1, research: 2, monitor: 3, skip: 4 };
  out.sort((a, b) => order[a.action] - order[b.action] || b.score - a.score);
  // at most two per category so the desk is not five variations of one thing
  const perCat = new Map<string, number>();
  const picked: DeskOpportunity[] = [];
  for (const o of out) {
    const n = perCat.get(o.category) || 0;
    if (n >= 2) continue;
    perCat.set(o.category, n + 1);
    picked.push(o);
    if (picked.length >= 8) break;
  }
  return { generatedAt: now, opportunities: picked, considered, excluded, profile: CREATOR_PROFILE };
}
