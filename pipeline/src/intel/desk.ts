/** fixed-date calendar moments (month, day); the movable ones are computed */
const CALENDAR_DATES: [RegExp, (year: number) => Date | undefined][] = [
  [/halloween/i, (y) => new Date(Date.UTC(y, 9, 31))],
  [/christmas|xmas|navidad/i, (y) => new Date(Date.UTC(y, 11, 25))],
  [/new year/i, (y) => new Date(Date.UTC(y, 0, 1))],
  [/valentine/i, (y) => new Date(Date.UTC(y, 1, 14))],
  [/day of the dead|d[ií]a de (?:los )?muertos/i, (y) => new Date(Date.UTC(y, 10, 2))],
  [/thanksgiving/i, (y) => nthWeekday(y, 10, 4, 4)],
  [/black friday/i, (y) => { const t = nthWeekday(y, 10, 4, 4); return t && new Date(t.getTime() + 864e5); }],
  [/cyber monday/i, (y) => { const t = nthWeekday(y, 10, 4, 4); return t && new Date(t.getTime() + 4 * 864e5); }],
  [/mother'?s day/i, (y) => nthWeekday(y, 4, 0, 2)],
  [/father'?s day/i, (y) => nthWeekday(y, 5, 0, 3)],
  [/diwali/i, (y) => ({ 2025: new Date(Date.UTC(2025, 9, 20)), 2026: new Date(Date.UTC(2026, 10, 8)), 2027: new Date(Date.UTC(2027, 9, 29)) } as Record<number, Date>)[y]],
  [/karwa ?chauth/i, (y) => ({ 2025: new Date(Date.UTC(2025, 9, 10)), 2026: new Date(Date.UTC(2026, 9, 29)) } as Record<number, Date>)[y]],
];
function nthWeekday(year: number, month: number, weekday: number, n: number): Date {
  const first = new Date(Date.UTC(year, month, 1));
  const offset = (weekday - first.getUTCDay() + 7) % 7;
  return new Date(Date.UTC(year, month, 1 + offset + 7 * (n - 1)));
}
/** days from `now` to the next occurrence of a calendar moment named in `name` (negative = passed within the last 10 days) */
export function calendarCountdown(name: string, now: string): { days: number; date: string } | undefined {
  const t = new Date(now);
  for (const [re, at] of CALENDAR_DATES) {
    if (!re.test(name)) continue;
    const y = t.getUTCFullYear();
    const candidates = [at(y - 1), at(y), at(y + 1)].filter((d): d is Date => !!d);
    for (const d of candidates) {
      const ms = d.getTime() - t.getTime();
      // the date starts at 00:00 UTC: "today" while inside that day, whole days before it, whole days after it
      const days = ms > 0 ? Math.ceil(ms / 864e5) : ms > -864e5 ? 0 : -Math.floor(-ms / 864e5);
      if (days >= -10 && days <= 400) return { days, date: d.toISOString().slice(0, 10) };
    }
  }
  return undefined;
}

export function timingOf(t: Trend, f: TrendFeatures, now: string): { timing: DeskTiming; why: string; score: number } {
  const w = t.windows['7d'];
  const historyHours = hoursBetween(t.firstDetected, now);
  // a cluster the crawler only started filling hours ago cannot show "measured growth": the count grows with the crawl
  const g = w.growth.basis === 'measured' && historyHours >= 24 ? w.growth.ratio : undefined;
  const ageDays = historyHours / 24;
  const gTxt = g != null ? `measured ${g}× over ${w.growth.windowHours}h` : 'growth not yet measured';
  // 4.0.1: a calendar moment is timed by the calendar, not by the crawl
  const cal = f.nameShape === 'calendar' ? calendarCountdown(t.name, now) : undefined;
  if (cal) {
    if (cal.days < 0) return { timing: 'cooling', why: `${t.name.replace(/^#/, '')} was ${-cal.days} day${cal.days === -1 ? '' : 's'} ago (${cal.date}) — the window has closed.`, score: 10 };
    if (cal.days === 0) return { timing: 'peaking', why: `Today is the day (${cal.date}): publish within hours or skip.`, score: 55 };
    if (cal.days <= 7) return { timing: 'accelerating', why: `${cal.days} day${cal.days === 1 ? '' : 's'} to the date (${cal.date}); ${w.newCreators} creators joined in the last 48h. Attention collapses the day after.`, score: cal.days <= 3 ? 85 : 75 };
    if (cal.days <= 21) return { timing: 'emerging', why: `${cal.days} days to the date (${cal.date}); early entries are being published now.`, score: 60 };
    return { timing: 'emerging', why: `${cal.days} days to the date (${cal.date}) — too early for a one-off piece.`, score: 30 };
  }
  // 4.0.1: when the cluster is too young for a measured growth, read the examples' own measured rates
  const measuredMix = f.coolingShare != null && f.acceleratingShare != null ? `${Math.round(f.coolingShare * 100)}% of the measured examples are past their peak, ${Math.round(f.acceleratingShare * 100)}% still accelerating` : undefined;
  if (historyHours < 24) {
    if (f.coolingShare != null && f.coolingShare >= 0.5 && (f.acceleratingShare ?? 0) < 0.3) return { timing: 'cooling', why: `First seen ${Math.round(historyHours)}h ago; ${measuredMix} — the examples that carried this are slowing.`, score: 25 };
    if (f.acceleratingShare != null && f.acceleratingShare >= 0.5) return { timing: 'accelerating', why: `First seen ${Math.round(historyHours)}h ago; ${measuredMix}; ${w.creators} independent creators so far (cluster growth itself needs 24h of history).`, score: 75 };
    return { timing: w.lifecycle === 'cooling' ? 'cooling' : 'emerging', why: `First seen ${Math.round(historyHours)}h ago — cluster growth is not measurable until it has 24h of history${measuredMix ? `; ${measuredMix}` : ''}; ${w.creators} independent creators so far.`, score: 50 };
  }
  if (ageDays >= 7 && g != null && g >= 1.5) return { timing: 'resurfacing', why: `First seen ${Math.round(ageDays)} days ago and ${gTxt} — attention is coming back.`, score: 65 };
  const tail = measuredMix ? ` ${measuredMix}.` : '';
  switch (w.lifecycle) {
    case 'emerging': return { timing: 'emerging', why: `${w.newCreators} creators joined in the last 48h; ${gTxt}.${tail}`, score: g != null && g < 1 ? 45 : 80 };
    case 'accelerating': return { timing: 'accelerating', why: `${gTxt}; ${w.newCreators} new creators in 48h.${tail}`, score: 90 };
    case 'breaking_out': return { timing: 'accelerating', why: `Momentum on ${t.platforms.length} sources; ${gTxt}.${tail}`, score: 85 };
    case 'peaking': return g != null && g >= 1.15 ? { timing: 'established', why: `High, still-growing attention (${gTxt}).${tail}`, score: 60 } : { timing: 'peaking', why: `Attention is high but flat (${gTxt}).${tail}`, score: 40 };
    case 'cooling': return { timing: 'cooling', why: `Attention is falling (${gTxt}).${tail}`, score: 15 };
    default: return { timing: 'emerging', why: `Evidence still forming.${tail}`, score: 35 };
  }
}

export function fitScore(t: Trend, f: TrendFeatures, category: string): { fit: number; approach: string[]; feasible: boolean; why: string; effort: [number, number] } {
  const cat = CATEGORY_FIT[category] ?? 0.5;
  const h = f.hooks;
  const n = Math.max(1, f.videos);
  const share = (k: string) => (h[k] || 0) / n;
  const approach: string[] = [];
  let tool = 0;
  if (share('animated') >= 0.2 || category === 'Animation & Art') { tool += 0.5; approach.push('animated or AI-generated characters and scenes'); }
  if (share('ai') >= 0.15) { tool += 0.3; approach.push('AI-generated video (text-to-video / image-to-video) with original characters'); }
  if (share('character') >= 0.15) { tool += 0.3; approach.push('a recurring original character (consistent design, voice and catchphrase)'); }
  if (share('music') >= 0.2 || category === 'Music') { tool += 0.3; approach.push('original music or an original parody track (no copyrighted audio)'); }
  if (share('storytime') >= 0.2) { tool += 0.15; approach.push('a short scripted story with a voiceover'); }
  if (share('pov') >= 0.15 || share('when') >= 0.15) { tool += 0.15; approach.push('a relatable "POV / when…" setup acted by a character'); }
  if (share('versus') >= 0.15 || share('escalation') >= 0.15) { tool += 0.1; approach.push('an escalating comparison or a ladder of levels'); }
  if (share('transformation') >= 0.15) { tool += 0.1; approach.push('a before → after reveal with a satisfying payoff'); }
  if (share('reaction') >= 0.4) { tool -= 0.2; approach.push('(reaction-heavy: use an original character reacting, not a repost)'); }
  if (share('tutorial') >= 0.3) { tool += 0.05; approach.push('an explainer told by a character, in under 60 seconds'); }
  if (!approach.length) approach.push('an original short-form skit using AI characters and fast editing');
  const langs = f.languages;
  const totalLang = Object.values(langs).reduce((a, b) => a + b, 0) || 1;
  const enEs = ((langs.en || 0) + (langs.es || 0)) / totalLang;
  const latinShare = Object.entries(langs).filter(([k]) => LATIN.has(k)).reduce((a, [, v]) => a + v, 0) / totalLang;
  const langFit = enEs >= 0.5 ? 1 : latinShare >= 0.5 ? 0.7 : 0.35;
  const typeFit = t.opportunity?.type === 'format' ? 1 : t.opportunity?.type === 'meme' ? 0.8 : t.opportunity?.type === 'event' ? 0.3 : 0.4;
  const shortForm = f.shortsShare >= 0.5 || (f.medianDurationSec ?? 61) <= 60;
  const feasible = cat >= 0.35 && !['Sports', 'News & Politics', 'Travel'].includes(category) && (shortForm || cat >= 0.7);
  const effort: [number, number] = shortForm ? [0.5, 2] : [1.5, 4];
  const fit = round(100 * clamp(0.35 * cat + 0.25 * clamp(tool, 0, 1) + 0.2 * langFit + 0.2 * typeFit, 0, 1), 0);
  const langTxt = enEs >= 0.5 ? 'mostly English/Spanish' : enEs >= 0.3 ? 'partly English/Spanish' : latinShare >= 0.5 ? 'mostly other Latin-script languages (adapt the wording)' : 'mostly non-Latin-script or unclear languages — adapt the concept, not the words';
  const why = feasible
    ? `${category} fits AI/animation production; ${shortForm ? 'short-form examples (median ' + (f.medianDurationSec ? Math.round(f.medianDurationSec) + 's' : 'under a minute') + ')' : 'longer examples'}; ${langTxt}.`
    : `${category} is hard to produce originally with AI/animation in two hours${shortForm ? '' : ' and the examples are long-form'}.`;
  return { fit, approach, feasible, why, effort };
}

export function monetizationFor(t: Trend, f: TrendFeatures, category: string): DeskOpportunity['monetization'] {
  const p = profileFor(category);
  const shortForm = f.shortsShare >= 0.5 || (f.medianDurationSec ?? 61) <= 60;
  const platforms = shortForm ? ['YouTube Shorts', 'TikTok', 'Instagram Reels'] : ['YouTube', 'Facebook'];
  const mechanisms = shortForm
    ? ['YouTube Shorts ad-revenue share (Partner Program)', 'TikTok Creator Rewards (videos ≥ 1 min)', 'Facebook/Instagram content monetization']
    : ['YouTube watch-page ads (Partner Program)', 'Facebook in-stream ads'];
  if (category === 'Music' || (f.hooks.music || 0) >= Math.max(2, f.videos * 0.3)) mechanisms.push('streams of the original track (distribution to Spotify/Apple), Content ID on re-uses');
  if (p.sponsorship >= 0.6) mechanisms.push('brand integrations once the format has an audience');
  if (p.affiliate >= 0.5) mechanisms.push('affiliate links in the description');
  const eligibility = [
    'YouTube Partner Program: 1,000 subscribers + 10M public Shorts views in 90 days (or 4,000 watch hours) — Shorts RPM is far below long-form',
    'TikTok Creator Rewards: 10,000 followers, 100,000 views in 30 days, original videos over one minute',
    'Reused or AI-mass-produced content can be ineligible under YouTube\'s "inauthentic content" policy — the execution must be original',
  ];
  return { platforms, mechanisms, eligibility, suitability: t.monetizationSuitability };
}

/** 4.0.1: evidence the desk can stand behind — a verified video that is not a stream, a long recording, a news clip or a
 *  text post, and that is either qualified (a hit or a breakout) or a recent mid-size success (≥100K views inside ten
 *  days: below the viral floor for its age, but a success in creator terms). The desk says which is which. A verified
 *  video below that is context only (shown in the lane, labelled as such). */
export function isCleanEvidence(r: VideoRecord): boolean {
  if (!r.verified) return false;
  if ((r.metrics.views ?? 0) < 10_000 && (r.metrics.likes ?? 0) < 100) return false;
  if (!isQualified(r) && !isStrongMidSize(r)) return false;
  return isUsableExample(r);
}
export function isQualified(r: VideoRecord): boolean { return r.state === 'verified_hit' || r.state === 'early_breakout'; }
/** a verified mid-size success: ≥100K views (≥1K likes on Bluesky) inside ten days, rejected only by the viral thresholds for its age */
export function isStrongMidSize(r: VideoRecord): boolean {
  if (r.state !== 'rejected') return false;
  if (!/below popularity thresholds|below breakout thresholds|past its peak|normal range/i.test(r.rejectedBy || '')) return false;
  const big = r.platform === 'bluesky' ? (r.metrics.likes ?? 0) >= 1_000 : (r.metrics.views ?? 0) >= 100_000;
  return big && r.ageHours != null && r.ageHours <= 240;
}
/** a verified video that can stand as an example of a short-form format at all (not a stream, long recording, news clip) */
export function isUsableExample(r: VideoRecord): boolean {
  if (LIVE_RE.test(r.title || '')) return false;
  if (r.durationSec != null && r.durationSec >= LONG_RECORDING_SEC) return false;
  if (r.platformCategory === 'News & Politics' || SPORTS_NEWS_RE.test(r.title || '')) return false;
  if (r.platform === 'bluesky' && !(r.metrics.likes != null && r.metrics.likes >= 100)) return false;
  return true;
}
/** context evidence: verified, candidate-sized and usable, but below the clean bar (smaller, or older than ten days) */
export function isContextEvidence(r: VideoRecord): boolean {
  if (!r.verified || r.state !== 'rejected' || isStrongMidSize(r)) return false;
  if ((r.metrics.views ?? 0) < 10_000 && (r.metrics.likes ?? 0) < 100) return false;
  if (!/below popularity thresholds|below breakout thresholds|past its peak|older than a week|cooling and below|normal range/i.test(r.rejectedBy || '')) return false;
  return isUsableExample(r);
}

type Ev = { e: Observation; r: VideoRecord; matched?: string };

/** the term of the cluster's name/signature that a title carries (what made the video evidence), if any */
function matchedTerm(t: Trend, title: string, sig: string[]): string | undefined {
  if (t.kind === 'format') return titleMatchesFormat(t, title) ? 'format rule' : undefined;
  if (titleCarries(t, title)) return t.name.replace(/^#/, '');
  const l = title.toLowerCase();
  return sig.find((x) => l.includes(x.toLowerCase()));
}

/** clean (qualified) and context (mid-size) evidence of a cluster, deduplicated, with the matched term */
function evidenceSets(t: Trend, byObs: Map<string, VideoRecord>): { clean: Ev[]; context: Ev[] } {
  let videos = t.evidence.filter((e) => e.kind === 'video');
  // relevance pools match on descriptions too; when enough examples match the format's rules in their TITLE, keep only those
  if (t.kind === 'format') { const strict = videos.filter((e) => titleMatchesFormat(t, e.title)); if (strict.length >= 3) videos = strict; }
  const sig = t.opportunity?.features.signature || [];
  const seen = new Set<string>();
  const clean: Ev[] = [];
  const context: Ev[] = [];
  for (const e of videos) {
    const k = exampleKey(e);
    if (seen.has(k)) continue;
    seen.add(k);
    const r = byObs.get(e.id);
    if (!r) continue;
    const matched = matchedTerm(t, r.title || e.title, sig);
    if (isCleanEvidence(r)) clean.push({ e, r, matched });
    else if (isContextEvidence(r)) context.push({ e, r, matched });
  }
  return { clean, context };
}

function toEvidence(x: Ev): DeskEvidence {
  const { e, r } = x;
  const v = r.velocity?.[0];
  return { id: e.id, platform: r.platform, url: r.url, title: r.title.slice(0, 110), creator: r.creator?.name, thumbnail: r.thumbnail || e.thumbnail, publishedAt: r.publishedAt, ageHours: r.ageHours, views: r.metrics.views, likes: r.metrics.likes, velocityPerHour: v?.perHour, velocityHours: v?.hours, velocityRatio: r.velocityRatio, state: r.state, kind: r.kind, verified: r.verified, durationSec: r.durationSec, language: r.language, matched: x.matched };
}

/** evidence ordered: title carries the name/signature first, then by size */
function evidenceFor(clean: Ev[], limit = 6): DeskEvidence[] {
  const size = (x: Ev) => x.r.metrics.views ?? x.r.metrics.likes ?? 0;
  return [...clean].sort((a, b) => Number(!!b.matched) - Number(!!a.matched) || size(b) - size(a)).slice(0, limit).map(toEvidence);
}

/** facts recomputed on the clean evidence (the cluster-level numbers include unverified, rejected and off-format videos) */
function cleanFeatures(f: TrendFeatures, clean: Ev[]): TrendFeatures {
  const creators = new Set(clean.map((x) => creatorKey(x.e)));
  const byCreator = new Map<string, number>();
  for (const x of clean) byCreator.set(creatorKey(x.e), (byCreator.get(creatorKey(x.e)) || 0) + 1);
  const new48 = new Set(clean.filter((x) => x.r.ageHours != null && x.r.ageHours <= 48).map((x) => creatorKey(x.e)));
  const views = clean.map((x) => x.r.metrics.views || 0);
  const total = views.reduce((a, b) => a + b, 0);
  const durations = clean.map((x) => x.r.durationSec).filter((d): d is number => d != null && d > 0).sort((a, b) => a - b);
  const langs: Record<string, number> = {};
  for (const x of clean) if (x.r.language) langs[x.r.language] = (langs[x.r.language] || 0) + 1;
  const measured = clean.filter((x) => x.r.velocityRatio != null && (x.r.velocity || []).reduce((a, v) => a + v.hours, 0) >= 2);
  // hooks on the clean titles only (a rejected "Top Halloween Songs" list must not turn a costume moment into a music approach)
  const hooks: Record<string, number> = {};
  for (const x of clean) for (const [name, re] of HOOKS) if (re.test(x.r.title || x.e.title)) hooks[name] = (hooks[name] || 0) + 1;
  return {
    ...f,
    hooks,
    creators: creators.size, videos: clean.length, directVideos: clean.length, newCreators48h: new48.size,
    repeatCreators: Array.from(byCreator.values()).filter((n) => n >= 2).length,
    dominance: total > 0 ? round(Math.max(...views) / total, 2) : f.dominance,
    shortsShare: clean.length ? round(clean.filter((x) => x.r.isShort).length / clean.length, 2) : f.shortsShare,
    medianDurationSec: durations.length ? durations[Math.floor(durations.length / 2)] : undefined,
    languages: langs,
    coolingShare: measured.length >= 2 ? round(measured.filter((x) => x.r.velocityRatio! < 0.8).length / measured.length, 2) : undefined,
    acceleratingShare: measured.length >= 2 ? round(measured.filter((x) => x.r.velocityRatio! >= 1.2).length / measured.length, 2) : undefined,
  };
}

/** 4.0.1: the category the verified examples themselves belong to (each video's own classification, falling back to its
 *  platform category), when a clear majority of the clean examples contradicts the cluster label — the cluster label
 *  is a vote over every member's text, including rejected and off-format videos ("halloween" → Music from one song list) */
function categoryFromEvidence(t: Trend, clean: Ev[]): { category: string; basis: 'cluster' | 'evidence' } {
  const votes = new Map<string, number>();
  for (const x of clean) {
    const own = x.r.category && x.r.category !== 'Other' ? x.r.category : undefined;
    const c = own || (x.r.platformCategory && PLATFORM_TO_TAXONOMY[x.r.platformCategory]);
    if (c) votes.set(c, (votes.get(c) || 0) + 1);
  }
  const known = Array.from(votes.values()).reduce((a, b) => a + b, 0);
  const top = Array.from(votes.entries()).sort((a, b) => b[1] - a[1])[0];
  // curated pools carry editorial categories; a microtrend's label is overridden by a clear majority of its clean examples
  if (t.kind !== 'format' && top && known >= 2 && top[1] / known >= 0.4 && top[1] >= 2 && top[0] !== t.category && (votes.get(t.category) || 0) < top[1]) return { category: top[0], basis: 'evidence' };
  // a pool whose verified examples are plainly sports/news is not what its editorial category says either
  if (t.kind === 'format' && top && known >= 3 && top[1] / known >= 0.75 && ['Sports', 'News & Politics'].includes(top[0]) && top[0] !== t.category) return { category: top[0], basis: 'evidence' };
  return { category: t.category, basis: 'cluster' };
}

function decideAction(t: Trend, f: TrendFeatures, timing: DeskTiming, fit: ReturnType<typeof fitScore>, evidenceScore: number, scaleOk: boolean): { action: DeskAction; why: string } {
  const type = t.opportunity?.type;
  const grade = t.windows['7d'].grade;
  if (!scaleOk && type !== 'event') return { action: 'monitor', why: 'Real adoption but small numbers so far (no example above 100K views / 1K likes).' };
  if (timing === 'cooling') return { action: 'skip', why: 'Attention is falling; a new entry would arrive after the audience moved on.' };
  if (type === 'event' && f.nameShape === 'calendar') return fit.fit >= 50 ? { action: 'participate', why: 'A calendar moment: worth one original piece before the date, not a series.' } : { action: 'skip', why: 'A calendar moment outside what AI/animation production does well.' };
  // a release or news topic (trailer, launch, match, award) is covered by many creators already: a topic, not a structure
  if (type === 'event' && (t.opportunity?.basis || []).some((b) => /named title\/release|news-style content|news\/person event/.test(b))) return { action: 'skip', why: 'A release or news topic people cover, not a structure to reuse.' };
  if (type === 'event') return { action: fit.feasible ? 'monitor' : 'skip', why: 'One video carries the attention; watch whether other creators adopt it before building a format on it.' };
  if (!fit.feasible) return { action: 'research', why: `Strong evidence but ${fit.why}` };
  if (grade === 'early' || f.creators < 4) return { action: 'monitor', why: `Only ${f.creators} independent creators with clean verified examples so far — promising, not yet proven.` };
  if (timing === 'peaking') return { action: 'participate', why: 'Crowded and flat: only with a sharp original angle.' };
  if (timing === 'established' && t.kind === 'format' && t.isGeneric) {
    if (fit.fit >= 65 && evidenceScore >= 55) return { action: 'create_today', why: `An evergreen format with ${f.creators} independent creators this week and a visible structure (${f.signature.slice(0, 3).join(', ') || 'repeat creators'}); it fits ${fit.effort[0]}–${fit.effort[1]}h of AI/animation production — the opportunity is the current signature and your execution.` };
    if (fit.fit >= 45) return { action: 'research', why: 'Evergreen and active, but only a moderate fit for AI/animation production — study the current signature before committing.' };
    return { action: 'monitor', why: 'Evergreen, but a weak fit for the creator profile.' };
  }
  if (type === 'meme' && f.creators < 5) return { action: 'monitor', why: `A specific moment with ${f.creators} creators — a meme needs five independent creators before it is worth production time.` };
  if ((timing === 'emerging' || timing === 'accelerating' || timing === 'resurfacing' || timing === 'established') && evidenceScore >= 55 && fit.fit >= 55) {
    return { action: 'create_today', why: `${f.creators} independent creators, ${timing} attention, and a format that fits ${fit.effort[0]}–${fit.effort[1]}h of AI/animation production.` };
  }
  if (evidenceScore >= 55) return { action: 'research', why: 'The evidence is solid but the creator fit is moderate — study the examples before committing production time.' };
  return { action: 'monitor', why: 'Evidence still developing.' };
}

/** 4.0.1: for a monitored item, the observation that would change the verdict */
function nextCheckFor(action: DeskAction, t: Trend, f: TrendFeatures, timing: DeskTiming, scaleOk: boolean, enEs: number): string | undefined {
  if (action !== 'monitor') return undefined;
  const type = t.opportunity?.type;
  const parts: string[] = [];
  if (type === 'event') parts.push('two or more other creators publishing their own version (the cluster would reclassify as a meme or a format)');
  if (!scaleOk) parts.push('one example clearing 100K views (or 1K likes on Bluesky)');
  if (f.creators < (type === 'meme' ? 5 : 4)) parts.push(`${(type === 'meme' ? 5 : 4) - f.creators} more independent creators with clean verified examples`);
  if (t.windows['7d'].grade === 'early') parts.push('a second collection confirming the growth (evidence grade is still "early")');
  if (enEs < 0.3) parts.push('examples in English or Spanish');
  if (timing === 'emerging' && hoursBetween(t.firstDetected, new Date().toISOString()) < 24) parts.push('24h of cluster history so growth can be measured');
  return parts.length ? `What would change the verdict: ${parts.join('; ')}.` : undefined;
}

/** 4.0.1: structures visible inside a pool — a word or pair of words shared by ≥3 independent creators' titles */
export function subFormatsOf(t: Trend, examples: Ev[], max = 3): SubFormat[] {
  const nameToks = new Set(tokenize(t.name.replace(/^#/, '')));
  const bad = (tok: string) => tok.length < 3 || STOPWORDS.has(tok) || isAnyStopword(tok) || nameToks.has(tok) || isBroadTopicTag(tok) || /^\d+$/.test(tok) || GENERIC_SUB.has(tok) || DESCRIPTOR.has(tok) || SIG_STOP.has(tok) || GENERIC_NAME.has(tok) || isDescriptorTag(tok);
  const byKey = new Map<string, { creators: Set<string>; ids: Set<string>; views: number }>();
  for (const x of examples) {
    const toks = tokenize(x.r.title || x.e.title).filter((tok) => !bad(tok));
    const keys = new Set<string>(toks);
    for (let i = 0; i + 1 < toks.length; i++) keys.add(`${toks[i]} ${toks[i + 1]}`);
    for (const k of keys) {
      const cur = byKey.get(k) || byKey.set(k, { creators: new Set(), ids: new Set(), views: 0 }).get(k)!;
      cur.creators.add(creatorKey(x.e)); cur.ids.add(x.e.id); cur.views = Math.max(cur.views, x.r.metrics.views || 0);
    }
  }
  const ranked = Array.from(byKey.entries()).filter(([, v]) => v.creators.size >= 3)
    .sort((a, b) => b[1].creators.size - a[1].creators.size || b[0].split(' ').length - a[0].split(' ').length || b[1].views - a[1].views);
  const out: SubFormat[] = [];
  const pickedIds: Set<string>[] = [];
  for (const [label, v] of ranked) {
    // the same examples under another label (a pair and one of its words, "indian theft" / "theft auto") are one sub-format
    const dup = pickedIds.some((ids) => { let inter = 0; for (const id of v.ids) if (ids.has(id)) inter++; return inter / Math.min(ids.size, v.ids.size) >= 0.6; });
    if (dup) continue;
    pickedIds.push(v.ids);
    out.push({ label, creators: v.creators.size, videos: v.ids.size, exampleIds: Array.from(v.ids).slice(0, 8), topViews: v.views || undefined });
    if (out.length >= max) break;
  }
  return out;
}
/** sub-format labels that are calendar tags belong to the calendar item, not to a pool */
const CAL_LABEL = /halloween|diwali|navratri|dussehra|durga|christmas|xmas|thanksgiving|karwa|chauth|eid|ramadan|easter|holi|valentine|newyear|new year|puja/i;
const GENERIC_SUB = new Set(['version', 'versions', 'audio', 'lyric', 'remix', 'feat', 'prod', 'video', 'videos', 'shorts', 'short', 'viral', 'trending', 'funny', 'best', 'new', 'full', 'official', 'part', 'episode', 'ep', 'live', 'stream', 'subscribe', 'like', 'comment', 'share', 'follow', 'channel', 'youtube', 'tiktok', 'instagram', 'reels', 'status', 'edit', 'edits', 'moments', 'moment', 'clip', 'clips', 'compilation', 'day', 'days', 'week', 'today', 'tonight', 'time', 'life', 'world', 'people', 'things', 'thing', 'one', 'two', 'three', 'first', 'last', 'every', 'never', 'always', 'real', 'true', 'fake', 'crazy', 'insane', 'epic', 'ultimate', 'amazing', 'awesome', 'cute', 'love', 'wait', 'watch', 'see', 'look', 'guy', 'guys', 'girl', 'girls', 'man', 'woman', 'boy', 'kid', 'kids', 'baby']);

export function buildDesk(trends: Trend[], records: VideoRecord[], now: string): DeskReport {
  const byObs = new Map(records.map((r) => [r.id, r]));
  const excluded: Record<string, number> = {};
  const debug = process.env.VR_DESK_DEBUG === '1';
  let current = '';
  const skip = (why: string) => { excluded[why] = (excluded[why] || 0) + 1; if (debug) console.log(`  desk skip: ${current} — ${why}`); };
  const out: DeskOpportunity[] = [];
  let considered = 0;
  for (const t of trends) {
    if (t.kind === 'topic') continue;
    considered++;
    current = `${t.kind} ${t.name}`;
    const op = t.opportunity;
    const w = t.windows['7d'];
    if (!op) { skip('not classified'); continue; }
    if (t.isNewsEvent) { skip('news / person event'); continue; }
    if (w.grade === 'insufficient') { skip('insufficient evidence'); continue; }
    if (op.features.nameShape === 'fragment') { skip('title fragment, not a format'); continue; }
    if (op.features.liveShare >= 0.5 && t.kind !== 'format') { skip('live streams, not a video format'); continue; }
    if (op.type === 'uncertain') { skip(t.kind === 'format' ? 'category pool without a visible structure this week' : t.isGeneric || op.features.descriptor ? 'generic tag or category' : 'no recognisable structure yet'); continue; }
    // evergreen format pools are allowed without a measured shift when adoption is broad (repeatable by definition)
    const evergreen = t.kind === 'format' && t.isGeneric;
    if (!t.qualified && op.type !== 'event' && !(evergreen && w.creators >= 6 && w.grade !== 'early')) { skip('not qualified (generic without measured shift)'); continue; }
    if (evergreen && w.creators > 80) { skip('category-level activity (too broad to be one opportunity)'); continue; }
    const { clean } = evidenceSets(t, byObs);
    if (clean.length < 3) { skip('fewer than 3 clean verified examples (hits, breakouts or ≥100K-view successes inside ten days; streams, long recordings, news clips, text posts and smaller videos excluded)'); continue; }
    const fClean = cleanFeatures(op.features, clean);
    const { category, basis: categoryBasis } = categoryFromEvidence(t, clean);
    if (category === 'News & Politics' || category === 'Sports') { skip(`the verified examples are ${category} content`); continue; }
    const timing = timingOf(t, fClean, now);
    if (evergreen && timing.timing === 'peaking') { timing.timing = 'established'; timing.why = `Evergreen format: ${w.creators} independent creators this week (${w.newCreators} new in 48h); ${timing.why.replace(/^Attention is high but flat/, 'attention is high and steady')}`; timing.score = 55; }
    if (evergreen && timing.timing === 'cooling' && hoursBetween(t.firstDetected, now) < 24) { timing.timing = 'established'; timing.score = 40; timing.why = `Evergreen format — the format itself does not cool, but ${timing.why.replace(/^First seen \d+h ago; /, '')}`; }
    const evidence = evidenceFor(clean);
    const largest = [...evidence].sort((a, b) => (b.views ?? b.likes ?? 0) - (a.views ?? a.likes ?? 0))[0];
    const scaleOk = evidence.some((e) => (e.views || 0) >= 100_000 || (e.platform === 'bluesky' && (e.likes || 0) >= 1_000));
    const langs = fClean.languages;
    const enEs = ((langs.en || 0) + (langs.es || 0)) / Math.max(1, clean.length);
    const fit = fitScore(t, fClean, category);
    const evidenceScore = round(clamp(0.35 * w.confidence + 0.25 * Math.min(100, 12 * fClean.creators) + 0.2 * (fClean.directVideos ? 100 : 30) + 0.2 * op.confidence, 0, 100), 0);
    let { action, why: actionWhy } = decideAction(t, fClean, timing.timing, fit, evidenceScore, scaleOk);
    if (action === 'create_today' && !(fit.feasible && fit.effort[1] <= 2)) { action = 'research'; actionWhy = `Worth studying, but an original variation needs ${fit.effort[0]}–${fit.effort[1]}h — above the two-hour window.`; }
    if (action === 'create_today' && enEs < 0.3) { action = 'research'; actionWhy = `Strong evidence, but ${Math.round(100 * (1 - enEs))}% of the clean examples are not in English/Spanish — adapt the mechanism after watching them.`; }
    if (action === 'participate' && enEs < 0.3) { action = 'monitor'; actionWhy = `A real moment, but ${Math.round(100 * (1 - enEs))}% of the examples are outside English/Spanish — not your audience's moment unless you adapt it.`; }
    if (action === 'skip') { skip(`skipped: ${timing.timing === 'cooling' ? 'cooling' : fClean.nameShape === 'calendar' ? 'calendar moment outside the creator fit (category or language)' : /release or news topic/.test(actionWhy) ? 'release / news topic, not a structure' : 'single event'}`); continue; }
    const why: string[] = [];
    const clusterVideos = t.evidence.filter((e) => e.kind === 'video').length;
    const qualified = clean.filter((x) => isQualified(x.r)).length;
    why.push(`${fClean.creators} independent creators with ${fClean.videos} verified examples in 7 days — ${qualified} qualified hit${qualified === 1 ? '' : 's'}/breakout${qualified === 1 ? '' : 's'}${clean.length > qualified ? ` and ${clean.length - qualified} mid-size success${clean.length - qualified === 1 ? '' : 'es'} (≥100K views, below the viral floor for their age)` : ''}${fClean.newCreators48h ? `; ${fClean.newCreators48h} creator${fClean.newCreators48h === 1 ? '' : 's'} published in the last 48h` : ''}${clusterVideos > clean.length ? `. ${clusterVideos - clean.length} other cluster video${clusterVideos - clean.length === 1 ? ' is' : 's are'} not counted (unverified, smaller, streams, long recordings, news clips or off-format)` : ''}.`);
    if (largest?.views) {
      const vr = largest.velocityRatio;
      const pace = vr == null ? '' : vr >= 1.2 ? ` (${vr}× its lifetime average — accelerating)` : vr >= 0.8 ? ` (${vr}× its lifetime average — holding its pace)` : ` (${vr}× its lifetime average — past its peak)`;
      why.push(`Largest example: ${fmt(largest.views)} views${largest.ageHours != null ? ` in ${largest.ageHours < 48 ? Math.round(largest.ageHours) + 'h' : Math.round(largest.ageHours / 24) + ' days'}` : ''}${largest.velocityPerHour ? `, +${fmt(largest.velocityPerHour)}/h measured${pace}` : ''}.`);
    }
    if (w.growth.basis === 'measured' && hoursBetween(t.firstDetected, now) >= 24) why.push(`Measured ${w.growth.metric}: ${w.growth.ratio}× over ${w.growth.windowHours}h.`);
    else why.push(`Cluster growth not yet measurable (history ${Math.round(hoursBetween(t.firstDetected, now))}h; measurements need 24h)${fClean.coolingShare != null ? ` — of the examples with a measured rate, ${Math.round(fClean.coolingShare * 100)}% are past their peak and ${Math.round((fClean.acceleratingShare || 0) * 100)}% still accelerating` : ''}.`);
    if (fClean.repeatCreators) why.push(`${fClean.repeatCreators} creator${fClean.repeatCreators === 1 ? ' repeats' : 's repeat'} the format among the clean examples — a sign it works more than once.`);
    if (fClean.signature.length) why.push(`Recognisable signature in titles: ${fClean.signature.slice(0, 4).join(', ')}.`);
    if (categoryBasis === 'evidence') why.push(`Category taken from the verified examples' own platform category (${category}); the cluster label said ${t.category}.`);
    if (t.platforms.length > 1) why.push(`Seen on ${t.platforms.join(', ')}.`);
    const cal = op.type === 'event' && fClean.nameShape === 'calendar' ? calendarCountdown(t.name, now) : undefined;
    const caution = op.type === 'event' && fClean.nameShape === 'calendar' ? `A calendar window${cal ? ` (${cal.days} day${cal.days === 1 ? '' : 's'} to ${cal.date})` : ''}: attention collapses right after the date — publish before it or skip; nothing evergreen is being built.`
      : fClean.dominance >= 0.5 && fClean.videos >= 3 ? `${Math.round(fClean.dominance * 100)}% of the clean examples' views is one video${largest ? ` (“${largest.title.slice(0, 50)}”)` : ''} — the format is less proven than the headline number.`
      : op.type === 'meme' ? 'Memes decay fast: the window is days, not weeks.'
        : evergreen && w.growth.basis === 'measured' && (w.growth.ratio ?? 1) < 1.5 ? 'An evergreen format: always active, so the opportunity is the current signature and your execution, not a new wave.' : undefined;
    const score = round(0.4 * evidenceScore + 0.3 * timing.score + 0.3 * fit.fit, 0);
    out.push({
      id: `desk:${t.id}`, trendId: t.id, name: t.name.replace(/^#/, ''), category, categoryBasis, type: op.type, typeConfidence: op.confidence,
      timing: timing.timing, timingWhy: timing.why, evidence, why,
      facts: { creators: fClean.creators, newCreators48h: fClean.newCreators48h, videos: fClean.videos, directVideos: fClean.directVideos, qualified, growth: w.growth.basis === 'measured' && hoursBetween(t.firstDetected, now) >= 24 ? w.growth.ratio : undefined, growthBasis: w.growth.basis === 'measured' && hoursBetween(t.firstDetected, now) >= 24 ? 'measured' : 'provisional', topViews: largest?.views, topVelocity: largest?.velocityPerHour, grade: w.grade },
      features: fClean,
      production: { feasibleIn2h: fit.feasible && fit.effort[1] <= 2, approach: fit.approach, why: fit.why, effortHours: fit.effort },
      monetization: monetizationFor(t, fClean, category),
      action, actionWhy, fit: fit.fit, evidenceScore, timingScore: timing.score, score, caution,
      nextCheck: nextCheckFor(action, t, fClean, timing.timing, scaleOk, enEs),
    });
  }
  // the owner's lane: current activity in the pools that fit AI/animation/characters/music production, shown
  // whether or not a pool is a specific opportunity (broad pools are category activity, not one opportunity)
  const LANE = ['ai_video', 'animation', 'animal_comedy', 'puppets', 'comedy_skit', 'short_film', 'music_video', 'cover_song', 'explainer', 'storytime'];
  const lane: LaneEntry[] = [];
  const obsById = new Map<string, Observation>();
  for (const t of trends) for (const e of t.evidence) if (e.kind === 'video') obsById.set(e.id, e);
  for (const id of LANE) {
    const t = trends.find((x) => x.id === `f_${id}`);
    if (!t) continue;
    // the whole relevance pool (every verified record the format rules admitted), not only the cluster's shipped evidence:
    // the lane is a watchlist of the owner's pools, and sub-formats need the full set of titles
    const poolRecs = records.filter((r) => (r.formats || []).includes(id) && r.verified && isUsableExample(r) && (r.ageHours == null || r.ageHours <= 240));
    const sig = t.opportunity?.features.signature || [];
    const asEv = (r: VideoRecord): Ev => { const e = obsById.get(r.id) || ({ id: r.id, kind: 'video', title: r.title, url: r.url, creator: r.creator ? { name: r.creator.name, url: r.creator.url } : undefined, video: { platform: r.platform, id: r.platformId, channelId: r.creator?.channelId } } as unknown as Observation); return { e, r, matched: matchedTerm(t, r.title, sig) }; };
    const clean = poolRecs.filter(isCleanEvidence).map(asEv);
    const context = poolRecs.filter(isContextEvidence).map(asEv);
    const all = [...clean, ...context];
    if (all.length < 2) continue;
    const creators = new Set(all.map((x) => creatorKey(x.e)));
    const new48 = new Set(all.filter((x) => x.r.ageHours != null && x.r.ageHours <= 48).map((x) => creatorKey(x.e)));
    const ev = evidenceFor(all, 4);
    const onDesk = out.find((o) => o.trendId === t.id);
    const subFormats = subFormatsOf(t, clean.length >= 6 ? clean : all);
    for (const sf of subFormats) { const ids = new Set(sf.exampleIds); sf.examples = evidenceFor(all.filter((x) => ids.has(x.e.id)), 4); }
    const note = onDesk ? `on the desk: ${onDesk.action.replace('_', ' ')}`
      : t.opportunity?.type === 'uncertain' && t.kind === 'format' ? `${creators.size} creators with verified examples this week, but no shared structure beyond the category in the cluster's titles${subFormats.length ? ' — the sub-formats below are the thing to study' : ''}`
        : t.windows['7d'].creators > 80 ? `${t.windows['7d'].creators} creators this week — category-level activity, too broad to be one opportunity${subFormats.length ? '; the sub-formats below are the thing to study' : '; use the signature and the examples'}`
          : clean.length < 3 ? `fewer than 3 clean verified examples this week (${clean.length} clean, ${context.length} smaller)` : 'did not clear the desk gate (see the excluded reasons)';
    lane.push({ trendId: t.id, name: t.name, creators: creators.size, videos: all.length, qualified: clean.filter((x) => isQualified(x.r)).length, newCreators48h: new48.size, topViews: ev[0]?.views, signature: t.opportunity?.features.signature.slice(0, 5) || [], evidence: ev, note, subFormats: subFormats.length ? subFormats : undefined });
    // 4.0.1: a sub-format with real adoption (≥4 independent creators, at least one qualified example, short-form) becomes a
    // "research" item on the desk — a structure found in titles, not a validated cluster, so never "create today"
    if (!onDesk && t.opportunity) {
      for (const sf of subFormats) {
        if (sf.creators < 4) continue;
        const ids = new Set(sf.exampleIds);
        const exs = all.filter((x) => ids.has(x.e.id));
        if (!exs.some((x) => isQualified(x.r))) continue;
        if (calendarCountdown(sf.label, now) || CAL_LABEL.test(sf.label) || out.some((o) => o.name.toLowerCase() === sf.label.toLowerCase())) continue;
        const fSub = cleanFeatures(t.opportunity.features, exs);
        fSub.signature = [sf.label, ...t.opportunity.features.signature.filter((w) => w !== sf.label)].slice(0, 5);
        const short = fSub.shortsShare >= 0.5 || (fSub.medianDurationSec ?? 61) <= 60;
        if (!short) continue;
        const { category, basis: categoryBasis } = categoryFromEvidence({ ...t, kind: 'microtrend' } as Trend, exs);
        if (category === 'News & Politics' || category === 'Sports') continue;
        const timing = timingOf(t, fSub, now);
        if (timing.timing === 'cooling') continue;
        const fit = fitScore(t, fSub, category);
        const evidence = evidenceFor(exs);
        const largest = [...evidence].sort((a, b) => (b.views ?? 0) - (a.views ?? 0))[0];
        const qualified = exs.filter((x) => isQualified(x.r)).length;
        const langs = fSub.languages;
        const enEs = ((langs.en || 0) + (langs.es || 0)) / Math.max(1, exs.length);
        const evidenceScore = round(clamp(0.25 * Math.min(100, 12 * fSub.creators) + 0.35 * Math.min(100, 25 * qualified) + 0.4 * 55, 0, 100), 0);
        const why = [
          `A structure visible inside the “${t.name}” pool, not a validated cluster: ${fSub.creators} independent creators share “${sf.label}” in their titles (${exs.length} verified examples, ${qualified} qualified hit${qualified === 1 ? '' : 's'}/breakout${qualified === 1 ? '' : 's'}).`,
          largest?.views ? `Largest example: ${fmt(largest.views)} views${largest.ageHours != null ? ` in ${largest.ageHours < 48 ? Math.round(largest.ageHours) + 'h' : Math.round(largest.ageHours / 24) + ' days'}` : ''}${largest.velocityPerHour ? `, +${fmt(largest.velocityPerHour)}/h measured${largest.velocityRatio != null ? ` (${largest.velocityRatio}× its lifetime average)` : ''}` : ''}.` : '',
          fSub.coolingShare != null ? `Of the examples with a measured rate, ${Math.round(fSub.coolingShare * 100)}% are past their peak and ${Math.round((fSub.acceleratingShare || 0) * 100)}% still accelerating.` : 'Growth is not measured for a sub-format (it is not tracked as a cluster yet).',
          enEs < 0.5 ? `${Math.round(100 * (1 - enEs))}% of the examples are outside English/Spanish — adapt the mechanism, not the words.` : '',
        ].filter(Boolean);
        out.push({
          id: `desk:sub:${t.id}:${sf.label.replace(/\s+/g, '_')}`, trendId: t.id, name: `${sf.label} · ${t.name}`, category, categoryBasis, type: 'format', typeConfidence: 50,
          timing: timing.timing, timingWhy: timing.why.replace(/^First seen \d+h ago[^;]*;?\s*/, '').replace(/^cluster growth is not measurable[^;]*;?\s*/i, '') || 'Sub-format timing comes from its examples’ measured rates.', evidence, why,
          facts: { creators: fSub.creators, newCreators48h: fSub.newCreators48h, videos: exs.length, directVideos: exs.length, qualified, growthBasis: 'provisional', topViews: largest?.views, topVelocity: largest?.velocityPerHour, grade: t.windows['7d'].grade },
          features: fSub,
          production: { feasibleIn2h: fit.feasible && fit.effort[1] <= 2, approach: fit.approach, why: fit.why, effortHours: fit.effort },
          monetization: monetizationFor(t, fSub, category),
          action: 'research', actionWhy: `Found by shared title words, not by a validated cluster: ${fSub.creators} creators, short-form, in your lane — open the examples and judge the mechanism before committing production time.`,
          fit: fit.fit, evidenceScore, timingScore: timing.score, score: round(0.4 * evidenceScore + 0.3 * timing.score + 0.3 * fit.fit, 0),
          caution: `“${sf.label}” is a keyword the titles share; the videos may share it for different reasons — the thumbnails and the examples decide whether this is one format.`,
        });
      }
    }
  }
  lane.sort((a, b) => (b.qualified || 0) - (a.qualified || 0) || b.newCreators48h - a.newCreators48h || b.creators - a.creators);
  const order: Record<DeskAction, number> = { create_today: 0, participate: 1, research: 2, monitor: 3, skip: 4 };
  out.sort((a, b) => order[a.action] - order[b.action] || b.score - a.score);
  // at most two per category so the desk is not five variations of one thing
  const perCat = new Map<string, number>();
  const picked: DeskOpportunity[] = [];
  for (const o of out) {
    const n = perCat.get(o.category) || 0;
    if (n >= 2) continue;
    perCat.set(o.category, n + 1);
    picked.push(o);
    if (picked.length >= 8) break;
  }
  return { generatedAt: now, opportunities: picked, lane, considered, excluded, profile: CREATOR_PROFILE };
}
